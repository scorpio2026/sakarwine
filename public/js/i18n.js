  let lang = 'my';
  const listeners = [];

  function interpolate(s, vars) {
    if (!vars) return s;
    return String(s).replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : ''));
  }

  function t(key, vars) {
    const pack = catalogs[lang] || catalogs.en;
    const s = pack[key] || catalogs.en[key] || key;
    return interpolate(s, vars);
  }

  function error(msg) {
    const key = ERROR_MAP[String(msg || '')];
    if (key) return t(key);
    return msg || t('errGeneric');
  }

  function setLang(code) {
    if (!catalogs[code]) code = 'my';
    lang = code;
    try {
      localStorage.setItem(STORAGE, code);
    } catch {
      /* ignore */
    }
    if (typeof document !== 'undefined') {
      document.documentElement.lang = code;
      document.documentElement.dataset.lang = code;
    }
    listeners.forEach((fn) => {
      try {
        fn(code);
      } catch {
        /* ignore */
      }
    });
  }

  function init() {
    let saved = null;
    try {
      saved = localStorage.getItem(STORAGE);
    } catch {
      saved = null;
    }
    setLang(catalogs[saved] ? saved : 'my');
  }

  function onChange(fn) {
    listeners.push(fn);
  }

  function switcherHtml(id) {
    return `<label class="lang-switch">
      <span>${t('language')}</span>
      <select id="${id}" aria-label="${t('language')}">
        ${LANGS.map((l) => `<option value="${l.code}" ${l.code === lang ? 'selected' : ''}>${l.native}</option>`).join('')}
      </select>
    </label>`;
  }

  function bindSwitcher(id, root) {
    const el = (root || document).querySelector(`#${id}`);
    if (!el) return;
    el.onchange = () => setLang(el.value);
  }

  function locale() {
    return LOCALES[lang] || 'en';
  }

  function formatWhen(ts) {
    try {
      return new Date(ts).toLocaleString(locale());
    } catch {
      return new Date(ts).toLocaleString();
    }
  }

  return {
    LANGS,
    catalogs,
    get lang() {
      return lang;
    },
    t,
    error,
    setLang,
    init,
    onChange,
    switcherHtml,
    bindSwitcher,
    locale,
    formatWhen
  };
